CREATE TABLE servico (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(100)   NOT NULL,
    duracao_minutos INTEGER        NOT NULL CHECK (duracao_minutos > 0),
    preco           NUMERIC(10, 2) NOT NULL CHECK (preco >= 0),
    ativo           BOOLEAN        NOT NULL DEFAULT TRUE
);

CREATE TABLE profissional (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100) NOT NULL,
    hora_inicio TIME         NOT NULL,
    hora_fim    TIME         NOT NULL,
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    CHECK (hora_fim > hora_inicio)
);

CREATE TABLE profissional_dia (
    profissional_id BIGINT      NOT NULL REFERENCES profissional (id),
    dia             VARCHAR(10) NOT NULL,
    PRIMARY KEY (profissional_id, dia)
);

CREATE TABLE profissional_servico (
    profissional_id BIGINT NOT NULL REFERENCES profissional (id),
    servico_id      BIGINT NOT NULL REFERENCES servico (id),
    PRIMARY KEY (profissional_id, servico_id)
);

CREATE TABLE agendamento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profissional_id  BIGINT       NOT NULL REFERENCES profissional (id),
    servico_id       BIGINT       NOT NULL REFERENCES servico (id),
    cliente_nome     VARCHAR(100) NOT NULL,
    cliente_telefone VARCHAR(20)  NOT NULL,
    inicio           TIMESTAMP    NOT NULL,
    fim              TIMESTAMP    NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    criado_em        TIMESTAMP    NOT NULL,
    CHECK (fim > inicio)
);

CREATE INDEX idx_agendamento_profissional_inicio ON agendamento (profissional_id, inicio);
