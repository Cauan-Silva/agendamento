-- Bloqueios avulsos: folga de um profissional (profissional_id preenchido)
-- ou o negócio inteiro fechado, como num feriado (profissional_id nulo)
CREATE TABLE bloqueio (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profissional_id BIGINT REFERENCES profissional (id),
    inicio          TIMESTAMP    NOT NULL,
    fim             TIMESTAMP    NOT NULL,
    motivo          VARCHAR(100),
    CHECK (fim > inicio)
);

CREATE INDEX idx_bloqueio_periodo ON bloqueio (inicio, fim);
